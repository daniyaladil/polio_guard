import 'dart:ui';

import 'package:latlong2/latlong.dart';

class HouseData {
  final String id;
  final String sector;
  final String address;
  final LatLng coordinates;
  final String status; // 'vaccinated', 'refused', 'absent', 'pending'
  final String workerId;
  final String familyName;

  HouseData({
    required this.id,
    required this.sector,
    required this.address,
    required this.coordinates,
    this.status = 'pending',
    required this.workerId,
    required this.familyName,
  });

  Map<String, dynamic> toJson() => {
    'id': id,
    'sector': sector,
    'address': address,
    'latitude': coordinates.latitude,
    'longitude': coordinates.longitude,
    'status': status,
    'workerId': workerId,
    'familyName': familyName,
  };

  factory HouseData.fromJson(Map<String, dynamic> json) => HouseData(
    id: json['id'],
    sector: json['sector'],
    address: json['address'],
    coordinates: LatLng(json['latitude'], json['longitude']),
    status: json['status'] ?? 'pending',
    workerId: json['workerId'],
    familyName: json['familyName'],
  );

  Color get statusColor {
    switch (status) {
      case 'vaccinated':
        return const Color(0xFF34A853); // Green
      case 'refused':
        return const Color(0xFFEA4335); // Red
      case 'absent':
        return const Color(0xFFFBBC04); // Yellow
      default:
        return const Color(0xFF9E9E9E); // Grey for pending
    }
  }

  String get statusLabel {
    switch (status) {
      case 'vaccinated':
        return '✅ Vaccinated';
      case 'refused':
        return '❌ Refused';
      case 'absent':
        return '⏳ Absent';
      default:
        return '⏳ Pending';
    }
  }
}

